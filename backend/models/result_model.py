from pydantic import BaseModel, Field
from typing import Optional, Dict, Any
from enum import Enum


class PipelineStatus(str, Enum):
    """Enumeration of possible pipeline outcome states."""
    COMPLETED = "completed"
    ERROR = "error"
    FATAL = "fatal"


class AnalysisResult(BaseModel):
    """
    Standardized response model returned by the orchestrator pipeline.
    This is the top-level structure sent back to the frontend via the API.
    """
    status: PipelineStatus = Field(
        ...,
        description="Overall pipeline execution status."
    )
    insights_summary: Optional[str] = Field(
        default=None,
        description="Human-readable markdown insights report generated by the ReportAgent."
    )
    generated_code: Optional[str] = Field(
        default=None,
        description="The Python/Pandas code that was generated and executed."
    )
    captured_output: Optional[str] = Field(
        default=None,
        description="Raw stdout captured during code execution."
    )
    error: Optional[str] = Field(
        default=None,
        description="Error message if the pipeline failed at any stage."
    )


class UploadResponse(BaseModel):
    """
    Response returned after a successful CSV file upload.
    """
    dataset_id: str = Field(
        ...,
        description="Unique identifier assigned to the uploaded dataset."
    )
    filename: str = Field(
        ...,
        description="Original filename of the uploaded CSV."
    )
    message: str = Field(
        default="File uploaded successfully.",
        description="Human-readable status message."
    )


class QueryRequest(BaseModel):
    """
    Request body for submitting an analysis query against an uploaded dataset.
    """
    dataset_id: str = Field(
        ...,
        description="The dataset_id returned from a previous upload."
    )
    query: str = Field(
        ...,
        min_length=3,
        description="Natural language analysis question (e.g. 'What is the average sales by region?')."
    )
