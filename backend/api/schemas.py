from typing import Optional
from pydantic import BaseModel, Field

class QueryRequest(BaseModel):
    query: str = Field(..., description="Natural language query asking to analyze the data")
    file_id: str = Field(..., description="Unique identifier for the uploaded CSV dataset")

class QueryResponse(BaseModel):
    status: str = Field(..., description="Pipeline status: 'completed', 'error', or 'fatal'")
    insights_summary: Optional[str] = Field(default=None, description="LLM-generated insights report")
    generated_code: Optional[str] = Field(default=None, description="The Python code that was generated")
    captured_output: Optional[str] = Field(default=None, description="Raw stdout from code execution")
    chart_image_base64: Optional[str] = Field(default=None, description="Base64 encoded chart image generated by the execution agent")
    error: Optional[str] = Field(default=None, description="Error message if pipeline failed")

class UploadResponse(BaseModel):
    status: str = Field(..., description="'success' or 'error'")
    file_id: str = Field(..., description="A unique identifier reference for the file")
    message: str = Field(..., description="User-friendly status message")
